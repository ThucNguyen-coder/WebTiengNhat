export const ALL_WORDS = TOPICS.flatMap((t) => t.words.map((wd) => ({ ...wd, topic: t.id })));

export const topicById = (id) => TOPICS.find((t) => t.id === id);

// Each topic is split into lessons of up to 5 words, followed by a game node.
export const LESSON_SIZE = 5;
export function lessonsOf(topic) {
  const out = [];
  for (let i = 0; i < topic.words.length; i += LESSON_SIZE) out.push(topic.words.slice(i, i + LESSON_SIZE));
  return out;
}
